export const QUESTIONS = questionDefinitions
    .slice()
    .sort((left, right) => {
        const leftCategory = CATEGORIES.findIndex(
            (category) => category.id === left.category,
        );
        const rightCategory = CATEGORIES.findIndex(
            (category) => category.id === right.category,
        );
        return leftCategory - rightCategory || left.id - right.id;
    })
    .map((question, index) => {
        const id = index + 1;
        return {
            ...question,
            id,
            title: question.title.replace(/^\d+\.\s*/, `${id}. `),
        };
    });
